using System.Reflection;
using Gaffer.Api.Versioning;
using Microsoft.Extensions.DependencyInjection;
using NJsonSchema;
using NJsonSchema.Generation;
using NSwag;
using NSwag.Generation.Processors;

namespace Gaffer.Api.Startups;

public static class SwaggerStartUp {
    public static void ConfigureSwagger(this IServiceCollection services, string productName) {
        for (var v = ApiVersioning.Min; v <= ApiVersioning.Current; v++) {
            AddSwaggerDocFor(services, productName, v);
        }
        AddOpenApiDocForAutogeneratedClient(services, productName);
    }

    private static void AddSwaggerDocFor(IServiceCollection services, string productName, int v) {
        var documentName = $"v{v}";
        services.AddSwaggerDocument((document, serviceProvider) => {
            document.SchemaSettings.SchemaNameGenerator = new DefaultSchemaNameGenerator();
            document.SchemaSettings.TypeNameGenerator = new DefaultTypeNameGenerator();
            document.OperationProcessors.Insert(0, new ApiVersionProcessor());
            document.DocumentName = documentName;
            document.Title = productName.ToUpper();
        });
    }

    private static void AddOpenApiDocForAutogeneratedClient(IServiceCollection services, string productName) {
        services.AddOpenApiDocument((options) => {
            options.DocumentName = "AutogeneratedClient";
            options.Title = productName;
            options.Version = ClientPackageVersion();
            options.PostProcess = document => {
                var openApiTags = new List<OpenApiTag>();
                for (var version = 1; version <= ApiVersioning.Current; version++) {
                    openApiTags.Add(new OpenApiTag { Name = $"v{version}" });
                }
                document.Tags = openApiTags;
            };
        });
    }

    /// <summary>Gaffer.Api.Client package version, stamped by Directory.Build.props as assembly metadata.</summary>
    private static string ClientPackageVersion() =>
        typeof(SwaggerStartUp).Assembly
            .GetCustomAttributes<AssemblyMetadataAttribute>()
            .Single(attribute => attribute.Key == "GafferClientVersion")
            .Value!;
}
